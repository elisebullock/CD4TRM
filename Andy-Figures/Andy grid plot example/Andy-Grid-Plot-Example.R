# make five random datasets to plot and arrange in 2 rows
# we want to align the frames of each plot
# notice how we implement nice log scale labels/ticks/grid lines in plots 1 and 5
# plot #6 is generated by ggarrange and is blank - fills up the bottom row. 
# the call to ggarrange tells you this

tp=seq(0,20,1)
d=data.frame(times=tp, y1=2^tp, y2=tp, y3=tp^3 + 10, y4=1-exp(-0.3*tp), y5=2^(-tp))

p1=ggplot(d, aes(x=times, y=y1)) +  theme_bw() +
  scale_y_continuous(limits=c(1, 2e6),
                     trans="log10",
                     breaks = as.numeric(1 %o% 10^(0:6)), minor_breaks = as.numeric(1:10 %o% 10^(0:6)),
                     labels = ggplot_scientific_notation_axes_labels) + 
  geom_point(size=pointsize) + my_theme_tweaks + 
  ggtitle("Plot 1") +
  xlab("Time post-treatment") + ylab("Cell numbers") 
  
p2=ggplot(d, aes(x=times, y=y2)) + geom_point(size=pointsize) + ggtitle("Plot 2") + theme_bw() +
  xlab("Time post-treatment") + ylab("Whatever")+ my_theme_tweaks 

p3=ggplot(d, aes(x=times, y=y3)) + geom_point(size=pointsize) + ggtitle("Plot 3") + theme_bw() +
  xlab("Time post-treatment") + ylab("Cell numbers") + theme_bw()+ my_theme_tweaks 

p4=ggplot(d, aes(x=times, y=y4)) + geom_line() + ggtitle("Plot 4") + 
  xlab("Time post-treatment") + ylab("Frequency") + theme_bw() + my_theme_tweaks

# this one looks a bit weird as minor breaks are at 3 * 10^x, but there are no labels there
# so you don't know what those lines mean. But I did this to stop the axis labels being too tight
# probably better to have no minor breaks (minor_breaks = NULL  below)
# remember "breaks" are where the numbers are... 
p5 = ggplot(d, aes(x=times, y=y5)) + theme_bw() + my_theme_tweaks + 
  scale_y_continuous(limits=c(3e-7, 1),
                     trans="log10",
                     breaks = as.numeric(1 %o% 10^(-7:0)), minor_breaks = as.numeric(c(1,3) %o% 10^(-7:0)),
                     labels = ggplot_scientific_notation_axes_labels) + 
  geom_point(colour="orange",size=pointsize) + 
  ggtitle("Plot 5") +   xlab("Time post-treatment") + ylab("Frequency") + 
  theme_bw()+ my_theme_tweaks 

gc()  # garbage collection
# this may give obscure warning messages – you can usually ignore them 
# "draw=F" means we just build the object but don't plot it yet
p.egg=ggarrange(plots=list(p1,p2,p3,p4,p5), nrow=2, draw=F)                                                          

